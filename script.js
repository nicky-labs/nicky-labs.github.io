function chooseLanguage(language, reloadEnglish = true) {
  const selected = ["en", "zh", "th"].includes(language) ? language : "en";
  localStorage.setItem("portfolio-language", selected);
  const url = new URL(window.location.href);
  if (selected === "en") url.searchParams.delete("lang"); else url.searchParams.set("lang", selected);
  history.replaceState({}, "", `${url.pathname}${url.search}${url.hash}`);
  if (selected === "en" && reloadEnglish) { window.location.reload(); return; }
  if (selected !== "en") applyTranslation(selected);
  $$(".language-switcher button").forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.lang === selected)));
}

const queryLanguage = new URLSearchParams(window.location.search).get("lang");
const storedLanguage = localStorage.getItem("portfolio-language");
const browserLanguage = navigator.language.toLowerCase().startsWith("zh") ? "zh" : navigator.language.toLowerCase().startsWith("th") ? "th" : "en";
const initialLanguage = ["en", "zh", "th"].includes(queryLanguage) ? queryLanguage : ["en", "zh", "th"].includes(storedLanguage) ? storedLanguage : browserLanguage;
chooseLanguage(initialLanguage, false);
$$(".language-switcher button").forEach((button) => button.addEventListener("click", () => chooseLanguage(button.dataset.lang)));

